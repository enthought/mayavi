"""Build-time helper that generates ``tvtk_classes.zip``."""

import ast
import os
import zipfile


def _zip_stamp(zip_path):
    """Return the generation stamp recorded in the ZIP at `zip_path`, or
    None if there is no ZIP or it predates stamps."""
    try:
        with zipfile.ZipFile(zip_path) as z:
            code = z.read('tvtk_classes/vtk_version.py').decode()
    except (OSError, KeyError, zipfile.BadZipFile):
        return None
    for line in code.splitlines():
        if line.startswith('generation_stamp = '):
            return ast.literal_eval(line.split('=', 1)[1].strip())
    return None


def gen_tvtk_classes_zip():
    """Generate ``tvtk/tvtk_classes.zip`` unless the one there is current.

    Current means generated by this generator, against this VTK, under this
    Python (see `tvtk.code_gen.generation_stamp`).  A build runs this more
    than once per install, and nothing changes in between, so the stamp also
    keeps the later runs from regenerating.
    """
    from tvtk.code_gen import TVTKGenerator, generation_stamp
    tvtk_dir = os.path.dirname(os.path.abspath(__file__))
    target = os.path.join(tvtk_dir, 'tvtk_classes.zip')
    stamp = generation_stamp()
    print('-'*70)
    if _zip_stamp(target) == stamp:
        print('TVTK classes are current (%s)' % stamp)
        print('-'*70)
        return
    print('Building TVTK classes (%s)...' % stamp, end=' ', flush=True)
    gen = TVTKGenerator('')
    try:
        gen.generate_code()
        # build_zip writes to the current directory
        cwd = os.getcwd()
        os.chdir(tvtk_dir)
        try:
            gen.build_zip(True)
        finally:
            os.chdir(cwd)
    finally:
        gen.clean()
    print('Done.')
    print('-'*70)
